//! Generates `$OUT_DIR/branding.rs`, the constants of `florastack_core::branding`, from `branding.toml` at the
//! repository root. The schema is strict: a missing, misspelled or unexpected key fails the build.

use std::error::Error;
use std::fmt::Write as _;
use std::path::PathBuf;
use std::{env, fs};

use serde::Deserialize;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Branding {
    display_name: String,
    project_extension: String,
    app_id: String,
    binaries: Binaries,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Binaries {
    gui: String,
    cli: String,
}

fn main() -> Result<(), Box<dyn Error>> {
    let path = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?).join("../../branding.toml");
    println!("cargo::rerun-if-changed={}", path.display());
    let text = fs::read_to_string(&path).map_err(|e| format!("cannot read {}: {e}", path.display()))?;
    let branding: Branding = toml::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;

    let constants = [
        ("DISPLAY_NAME", "Name shown to people: window titles, menus, installers, file metadata.", &branding.display_name),
        ("GUI_BINARY", "Executable name of the desktop app.", &branding.binaries.gui),
        ("CLI_BINARY", "Executable name of the command-line tool.", &branding.binaries.cli),
        ("PROJECT_EXTENSION", "Extension of a project folder, including the leading dot.", &branding.project_extension),
        ("APP_ID", "Reverse-DNS application ID (Flatpak, desktop entries, macOS bundle identifier).", &branding.app_id),
    ];
    let mut out = String::from("// Generated by build.rs from branding.toml; edit that file instead.\n");
    for (name, doc, value) in constants {
        // `{:?}` writes a correctly escaped Rust string literal.
        writeln!(out, "\n/// {doc}\npub const {name}: &str = {value:?};")?;
    }
    fs::write(PathBuf::from(env::var("OUT_DIR")?).join("branding.rs"), out)?;
    Ok(())
}
